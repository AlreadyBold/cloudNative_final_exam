#!/bin/bash
# =====================================================================
# 01_network.sh : 내약통한눈에 컨테이너들이 함께 쓸 사용자 정의 브리지 네트워크 생성
#
#  - 같은 사용자 정의 네트워크에 붙은 컨테이너끼리는 "컨테이너 이름"으로 서로를 찾을 수 있다.
#    (도커 내장 DNS 127.0.0.11 이 alyak-mysql → 172.x.x.x 처럼 이름을 IP 로 바꿔 준다)
#  - 그래서 서버 설정에 IP 대신 alyak-mysql, alyak-redis 같은 이름을 쓸 수 있다.
#  - 기본 bridge 네트워크는 이름 기반 DNS 를 지원하지 않으므로 반드시 새로 만든다.
# =====================================================================
set -e   # 명령이 하나라도 실패하면 즉시 중단

# --driver bridge : 한 대의 호스트 안에서 컨테이너끼리 통신하는 브리지 방식 네트워크
docker network create --driver bridge alyak-net
